import { language, type Lang } from './languages.ts';

export interface Ui {
	/** Skip link to the text */
	skipToText: string;
	/** Name of the top bar navigation */
	book: string;
	/** Link to the table of contents */
	contents: string;
	/** Title of the section list */
	sections: string;
	sectionCount: (count: number) => string;
	sectionOf: (current: number, total: number) => string;
	chapter: string;
	part: (number: number) => string;
	/** The front matter group of the TOC (preface and introduction) */
	introduction: string;
	/** „Als Nächstes“: the next page in the book */
	next: string;
	previous: string;
	/** Name of the navigation after the text */
	continueInBook: string;
	backTo: (title: string) => string;
	backToContents: string;
	/** Start or resume reading */
	read: string;
	/** „Lesen: Vorwort“: where „Lesen“ on the homepage leads */
	readTitle: (title: string) => string;
	/** „Kapitel 1“ */
	chapterNumber: (number: number) => string;
	articleCount: (count: number) => string;
	/** The front matter's place in the book */
	beforeChapters: string;
	/** The appendix's place in the book */
	afterChapters: string;
	/** Credit line of the homepage */
	credit: (since: number, parts: number, articles: number) => string;
	/** The book's subtitle, as the colophon of the language translates it */
	subtitle: string;
	modeLegend: string;
	modeLight: string;
	modeDark: string;
	modeSystem: string;
	/** Accessible name of the mode toggle button */
	modeToggleDark: string;
	languageLabel: string;
	/** Button beside the language select: goes to the page in the chosen language */
	languageGo: string;
	search: string;
	searchPlaceholder: string;
	searchNoResults: string;
	close: string;
	readingTime: (minutes: number) => string;
}

type Forms = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string };

/** The plural form of a word for a count, by the rules of the language */
const plural = (lang: Lang, count: number, forms: Forms): string =>
	forms[new Intl.PluralRules(language(lang).htmlLang).select(count)] ?? forms.other;

