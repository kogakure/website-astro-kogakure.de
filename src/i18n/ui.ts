/** Joins the parts of a credit line: „Kapitel 1, 10 Artikel“, 「第1章、全10編」 */
export const joinCredit = (lang: Lang, parts: string[]): string =>
	parts.join(lang === 'ja' || lang === 'zh' ? '、' : ', ');
